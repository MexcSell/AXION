// Regenerates docs/screenshots/*.png (key screens, 8 skin×theme combos, responsive sizes).
import { chromium } from 'playwright';
import { signIn } from './_session.mjs';
import { mkdirSync } from 'node:fs';
import { resolveBase } from './_base.mjs';
const base = resolveBase();
const out = 'docs/screenshots'; mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || '/root/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome' });
const shot = async (name, path, { w = 1672, h = 941, theme = 'dark', skin = 'luminous', wait = 2600, act } = {}) => {
  const ctx = await b.newContext({ viewport: { width: w, height: h } });
  await signIn(ctx);
  await ctx.addInitScript(([theme, skin]) => localStorage.setItem('axion.settings.v1', JSON.stringify({ state: { themeMode: theme, skin, motion: 'full' }, version: 0 })), [theme, skin]);
  const p = await ctx.newPage();
  await p.goto(base + path, { waitUntil: 'networkidle' }); await p.waitForTimeout(wait);
  if (act) await act(p);
  await p.screenshot({ path: `${out}/${name}.png` }); await ctx.close();
};
